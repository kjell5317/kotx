import {
  postIssueComment,
  splitRepo,
  type HitlRequestPayload,
  type SubjectType,
} from "@kotx/shared";
import type { Octokit } from "@octokit/rest";

const FOOTER = (runId: number) =>
  `\n\n---\n🤖 Generated by the kotx Codex agent · run #${runId} · do not auto-merge`;

export interface SubjectDetails {
  title: string;
  body: string;
}

export async function fetchSubject(
  octokit: Octokit,
  repoFullName: string,
  type: SubjectType,
  number: number,
): Promise<SubjectDetails> {
  const [owner, repo] = splitRepo(repoFullName);
  if (type === "pull_request") {
    const res = await octokit.pulls.get({ owner, repo, pull_number: number });
    return { title: res.data.title ?? "", body: res.data.body ?? "" };
  }
  const res = await octokit.issues.get({ owner, repo, issue_number: number });
  return { title: res.data.title ?? "", body: res.data.body ?? "" };
}

/**
 * Open a PR for the agent branch, or update the existing open one. Returns the
 * PR number. Links the issue with "Closes #NN" (SPEC §16 Q2 default).
 */
export async function openOrUpdatePr(
  octokit: Octokit,
  opts: {
    repoFullName: string;
    branch: string;
    base: string;
    issueNumber: number;
    title: string;
    resultMd: string;
    runId: number;
  },
): Promise<number> {
  const [owner, repo] = splitRepo(opts.repoFullName);
  const body =
    `Closes #${opts.issueNumber}\n\n${opts.resultMd}` + FOOTER(opts.runId);

  const existing = await octokit.pulls.list({
    owner,
    repo,
    head: `${owner}:${opts.branch}`,
    state: "open",
  });

  if (existing.data.length > 0) {
    const prNumber = existing.data[0]!.number;
    await octokit.pulls.update({ owner, repo, pull_number: prNumber, body });
    await postIssueComment(
      octokit,
      opts.repoFullName,
      prNumber,
      `🤖 Updated with new commits (run #${opts.runId}).`,
    );
    return prNumber;
  }

  const created = await octokit.pulls.create({
    owner,
    repo,
    title: `[agent] ${opts.title}`,
    head: opts.branch,
    base: opts.base,
    body,
  });
  return created.data.number;
}

export async function postReview(
  octokit: Octokit,
  repoFullName: string,
  prNumber: number,
  reviewMd: string,
  runId: number,
): Promise<void> {
  await postIssueComment(
    octokit,
    repoFullName,
    prNumber,
    reviewMd + FOOTER(runId),
  );
}

export async function postHitlComment(
  octokit: Octokit,
  repoFullName: string,
  issueNumber: number,
  hitl: HitlRequestPayload,
  runId: number,
): Promise<number> {
  const alts = hitl.alternatives.length
    ? hitl.alternatives.map((a) => `- ${a}`).join("\n")
    : "_none provided_";
  const body =
    `🛑 **Approval needed** (run #${runId}, risk: **${hitl.risk}**)\n\n` +
    `**Why:** ${hitl.reason}\n\n` +
    `**Proposed action:** ${hitl.proposed_action}\n\n` +
    `**Alternatives:**\n${alts}\n\n` +
    `Reply \`/agent approve\` to proceed or \`/agent reject\` to cancel. ` +
    `Anything after the command is passed to the agent as a note.`;
  return postIssueComment(octokit, repoFullName, issueNumber, body);
}

export async function postFailureComment(
  octokit: Octokit,
  repoFullName: string,
  issueNumber: number,
  outcome: string,
  runId: number,
): Promise<void> {
  await postIssueComment(
    octokit,
    repoFullName,
    issueNumber,
    `🤖 Task ${outcome} (run #${runId}). See the agent host logs for details.`,
  );
}
